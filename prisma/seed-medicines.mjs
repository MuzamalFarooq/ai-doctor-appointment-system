async function main() {
  console.log('--- Starting Medicine Database Seeding ---');

  // 1. Seed Categories
  console.log(`Seeding ${categories.length} therapeutic categories...`);
  for (const cat of categories) {
    await prisma.medicineCategory.upsert({
      where: { slug: cat.slug },
      update: {
        name: cat.name,
        description: cat.description,
        icon: cat.icon,
        subcategories: cat.subcategories,
        displayOrder: cat.displayOrder,
        isActive: true,
      },
      create: {
        name: cat.name,
        slug: cat.slug,
        description: cat.description,
        icon: cat.icon,
        subcategories: cat.subcategories,
        displayOrder: cat.displayOrder,
        isActive: true,
      },
    });
  }
  console.log('✓ Categories successfully seeded.');

  // 2. Seed Medicines & Batches
  console.log(`Seeding ${medicines.length} legitimate catalog items with inventory batches...`);
  let createdCount = 0;

  for (const item of medicines) {
    const { batches, ...medData } = item;
    
    const productRecord = await prisma.medicineProduct.upsert({
      where: { catalogKey: item.catalogKey },
      update: {
        ...medData,
        demoData: false,
        isActive: true,
      },
      create: {
        ...medData,
        demoData: false,
        isActive: true,
      },
    });

    if (batches && batches.length > 0) {
      for (const batch of batches) {
        await prisma.medicineBatch.upsert({
          where: {
            medicineId_batchNumber: {
              medicineId: productRecord.id,
              batchNumber: batch.batchNumber,
            },
          },
          update: {
            expiryDate: batch.expiryDate,
            quantity: batch.quantity,
            initialQuantity: batch.initialQuantity,
          },
          create: {
            medicineId: productRecord.id,
            batchNumber: batch.batchNumber,
            expiryDate: batch.expiryDate,
            quantity: batch.quantity,
            initialQuantity: batch.initialQuantity,
          },
        });
      }
    }
    createdCount++;
  }

  console.log(`✓ Processed ${createdCount} medicines with batches successfully.`);
  const totalInDb = await prisma.medicineProduct.count();
  const totalCategories = await prisma.medicineCategory.count();
  const totalBatches = await prisma.medicineBatch.count();
  console.log(`Database summary: ${totalCategories} categories, ${totalInDb} products, ${totalBatches} active batches.`);
  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error('Seeding error:', e);
  await prisma.$disconnect();
  process.exit(1);
});
